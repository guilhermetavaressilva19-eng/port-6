function modoEdicao(ativo) {
  document.getElementById("dialogTitle").hidden = ativo;
  document.getElementById("dialogText").hidden = ativo;
  document.getElementById("editorArea").hidden = !ativo;
  document.getElementById("editEssay").hidden = ativo;
  document.getElementById("saveEssay").hidden = !ativo;
}

/* FECHAR REDAÇÃO */

function fecharRedacao() {
  const dialog = document.getElementById("essayDialog");

  if (dialog && dialog.open) {
    dialog.close();
  }

  redacaoAtual = null;
}

/* SALVAR EDIÇÃO */

function salvarRedacao() {
  const redacao = redacoes.find(
    r => r.id === redacaoAtual
  );

  if (!redacao) return;

  const titulo = document
    .getElementById("essayTitle")
    .value.trim();

  const texto = document
    .getElementById("essayText")
    .value;

  const status = document.getElementById("saveStatus");

  if (!titulo) {
    status.textContent = "Digite um título.";
    return;
  }

  const tituloAnterior = redacao.titulo;
  const textoAnterior = redacao.texto;

  redacao.titulo = titulo;
  redacao.texto = texto;

  if (!salvarEdicao(redacao)) {
    redacao.titulo = tituloAnterior;
    redacao.texto = textoAnterior;
    status.textContent =
      "Não foi possível salvar neste navegador.";
    return;
  }

  const pesquisa = document.getElementById("search");

  mostrarRedacoes(pesquisa ? pesquisa.value : "");

  document.getElementById("dialogTitle").textContent =
    redacao.titulo;

  document.getElementById("dialogText").textContent =
    redacao.texto;

  modoEdicao(false);

  status.textContent =
    "Redação salva neste navegador!";
}

/* MENU PARA CELULAR */

function configurarMenu() {
  const botao = document.getElementById("menuToggle");
  const nav = document.getElementById("nav");

  if (!botao || !nav) return;

  botao.addEventListener("click", () => {
    const aberto = nav.classList.toggle("open");

    botao.setAttribute(
      "aria-expanded",
      String(aberto)
    );
  });

  nav.querySelectorAll("a").forEach(link => {
    link.addEventListener("click", () => {
      nav.classList.remove("open");
      botao.setAttribute("aria-expanded", "false");
    });
  });
}

/* ANIMAÇÕES AO ROLAR */

function configurarAnimacoes() {
  const itens = document.querySelectorAll(".reveal");

  if (!("IntersectionObserver" in window)) {
    itens.forEach(item => {
      item.classList.add("visible");
    });
    return;
  }

  const observer = new IntersectionObserver(
    entradas => {
      entradas.forEach(entrada => {
        if (entrada.isIntersecting) {
          entrada.target.classList.add("visible");
          observer.unobserve(entrada.target);
        }
      });
    },
    { threshold: 0.08 }
  );

  itens.forEach(item => observer.observe(item));
}

/* BARRA DE PROGRESSO */

function configurarProgresso() {
  const barra = document.getElementById("progress");
  if (!barra) return;

  function atualizar() {
    const maximo =
      document.documentElement.scrollHeight -
      window.innerHeight;

    const percentual = maximo > 0
      ? (window.scrollY / maximo) * 100
      : 0;

    barra.style.width = `${percentual}%`;
  }

  window.addEventListener(
    "scroll",
    atualizar,
    { passive: true }
  );

  atualizar();
}

